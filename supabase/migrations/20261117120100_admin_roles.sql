-- 10f (owner's request 2026-11-17): administration roles that can be set up. SPEC §15.
--  - admin_permissions: the fixed list, one per area of /admin, to read or to act;
--  - admin_roles / admin_role_permissions: named roles and their ticked permissions; three at the
--    start (Admin: everything but team.manage; Modérateur; Observateur: read only);
--  - admin_users.role_id: every admin account has one role. The super admin stays outside this
--    system: unique, every permission, untouchable (super_admins, Phase 5a-ter);
--  - has_admin_permission(p): the second factor (aal2) and the permission; it replaces is_admin()
--    in every admin function (end of this file), is_admin() staying « any role, aal2 »;
--  - team.manage is never given to a role: only the super admin manages the team;
--  - a member account given a role leaves the site as a member while it has it (hidden_reason
--    « staff », its requests closed with the usual neutral notice); the role taken back, the
--    profile is as before. A guard on profiles keeps it so: an account with a role cannot act as
--    a member;
--  - every change of the team is logged (who, what, when, before and after), read in Historique.

