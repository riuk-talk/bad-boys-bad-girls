-- The roles, their permissions and how many accounts hold each.
create function public.admin_roles_list()
returns table (id smallint, name text, description text, editable boolean, permissions text[], members integer)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  return query
    select r.id, r.name, r.description, r.editable,
      coalesce((select array_agg(rp.permission order by p.position) from public.admin_role_permissions rp
                join public.admin_permissions p on p.key = rp.permission where rp.role_id = r.id), '{}'),
      (select count(*)::integer from public.admin_users a where a.role_id = r.id)
    from public.admin_roles r
    order by r.id;
end;
$$;

-- The permissions that can be ticked, in order (team.manage is not one of them).
create function public.admin_permission_keys()
returns table (key text, kind text)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  return query select p.key, p.kind from public.admin_permissions p where p.key <> 'team.manage' order by p.position;
end;
$$;

-- The team: the super admins (untouchable) and every account with a role, with whether the
-- second factor is set up. The e-mail is shown here only, to the super admin.
create function public.admin_team()
returns table (user_id uuid, email text, pseudo text, role_id smallint, role_name text,
  is_super_admin boolean, has_second_factor boolean, granted_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  return query
    select u.id, u.email::text, p.pseudo::text, a.role_id, r.name, s.user_id is not null,
      exists (select 1 from auth.mfa_factors f where f.user_id = u.id and f.status = 'verified'),
      coalesce(a.created_at, s.created_at)
    from auth.users u
    left join public.admin_users a on a.user_id = u.id
    left join public.super_admins s on s.user_id = u.id
    left join public.admin_roles r on r.id = a.role_id
    left join public.profiles p on p.id = u.id
    where a.user_id is not null or s.user_id is not null
    order by (s.user_id is not null) desc, coalesce(a.created_at, s.created_at);
end;
$$;

-- Give a role to an existing account (exact e-mail, or exact pseudo), or change it.
create function public.admin_grant_role(p_account text, p_role smallint)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  q text := btrim(coalesce(p_account, ''));
  target uuid;
  held_role smallint;
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  if q = '' then raise exception 'not_found' using errcode = 'P0002'; end if;
  if position('@' in q) > 0 then
    select u.id into target from auth.users u where lower(u.email) = lower(q) and u.deleted_at is null;
  else
    select p.id into target from public.profiles p where lower(p.pseudo::text) = lower(q);
  end if;
  if target is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  if exists (select 1 from public.super_admins s where s.user_id = target) then
    raise exception 'super_admin_protected' using errcode = '42501';
  end if;
  if not exists (select 1 from public.admin_roles r where r.id = p_role) then
    raise exception 'invalid_role' using errcode = '22023';
  end if;
  select a.role_id into held_role from public.admin_users a where a.user_id = target for update;
  if held_role is null then
    insert into public.admin_users (user_id, role_id, granted_by, note)
    values (target, p_role, (select auth.uid()), 'Équipe');
    insert into public.admin_team_log (actor_id, action, target_user_id, role_id, before, after)
    values ((select auth.uid()), 'grant', target, p_role, null,
            jsonb_build_object('role', (select r.name from public.admin_roles r where r.id = p_role)));
  elsif held_role <> p_role then
    update public.admin_users set role_id = p_role where user_id = target;
    insert into public.admin_team_log (actor_id, action, target_user_id, role_id, before, after)
    values ((select auth.uid()), 'change_role', target, p_role,
            jsonb_build_object('role', (select r.name from public.admin_roles r where r.id = held_role)),
            jsonb_build_object('role', (select r.name from public.admin_roles r where r.id = p_role)));
  end if;
  return target;
end;
$$;

-- Take the role back: the account is a member again, its profile as it was.
create function public.admin_revoke_role(p_user uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare a public.admin_users;
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  if exists (select 1 from public.super_admins s where s.user_id = p_user) then
    raise exception 'super_admin_protected' using errcode = '42501';
  end if;
  select * into a from public.admin_users where user_id = p_user for update;
  if not found then raise exception 'not_found' using errcode = 'P0002'; end if;
  delete from public.admin_users where user_id = p_user;
  insert into public.admin_team_log (actor_id, action, target_user_id, role_id, before, after)
  values ((select auth.uid()), 'revoke', p_user, a.role_id,
          jsonb_build_object('role', (select r.name from public.admin_roles r where r.id = a.role_id)), null);
end;
$$;

-- Create a role (no p_role) or change one: name, description, ticked permissions.
create function public.admin_save_role(p_name text, p_permissions text[], p_role smallint default null,
  p_description text default null)
returns smallint language plpgsql security definer set search_path = '' as $$
declare
  role_name text := btrim(coalesce(p_name, ''));
  motive text := nullif(btrim(coalesce(p_description, '')), '');
  perms text[] := coalesce(p_permissions, '{}');
  saved smallint;
  before_state jsonb;
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  if char_length(role_name) not between 2 and 40 then raise exception 'invalid_name' using errcode = '23514'; end if;
  if motive is not null and char_length(motive) > 200 then raise exception 'invalid_description' using errcode = '23514'; end if;
  if 'team.manage' = any (perms) then raise exception 'team_manage_reserved' using errcode = '42501'; end if;
  if exists (select 1 from unnest(perms) x where not exists (select 1 from public.admin_permissions p where p.key = x)) then
    raise exception 'invalid_permission' using errcode = '22023';
  end if;
  if exists (select 1 from public.admin_roles r where lower(r.name) = lower(role_name) and r.id is distinct from p_role) then
    raise exception 'role_name_taken' using errcode = '23505';
  end if;
  if p_role is null then
    insert into public.admin_roles (name, description) values (role_name, motive) returning id into saved;
  else
    select private.admin_role_snapshot(r.id) into before_state from public.admin_roles r where r.id = p_role and r.editable for update;
    if before_state is null then raise exception 'not_found' using errcode = 'P0002'; end if;
    update public.admin_roles set name = role_name, description = motive, updated_at = now() where id = p_role;
    delete from public.admin_role_permissions where role_id = p_role;
    saved := p_role;
  end if;
  insert into public.admin_role_permissions (role_id, permission)
  select saved, x from unnest(perms) x group by x;
  insert into public.admin_team_log (actor_id, action, role_id, before, after)
  values ((select auth.uid()), case when p_role is null then 'role_create' else 'role_update' end, saved,
          before_state, private.admin_role_snapshot(saved));
  return saved;
end;
$$;

-- Delete a role nobody holds.
create function public.admin_delete_role(p_role smallint)
returns void language plpgsql security definer set search_path = '' as $$
declare before_state jsonb;
begin
  if not public.has_admin_permission('team.manage') then raise exception 'admin_only' using errcode = '42501'; end if;
  select private.admin_role_snapshot(r.id) into before_state from public.admin_roles r where r.id = p_role and r.editable for update;
  if before_state is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  if exists (select 1 from public.admin_users a where a.role_id = p_role) then
    raise exception 'role_in_use' using errcode = '23503';
  end if;
  delete from public.admin_roles where id = p_role;
  insert into public.admin_team_log (actor_id, action, role_id, before, after)
  values ((select auth.uid()), 'role_delete', p_role, before_state, null);
end;
$$;

-- The team log in Historique.
create function public.admin_team_history(p_limit integer default 100)
returns table (id bigint, created_at timestamptz, actor text, action text, target text,
  before jsonb, after jsonb)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.has_admin_permission('history.view') then raise exception 'admin_only' using errcode = '42501'; end if;
  return query
    select l.id, l.created_at,
      coalesce((select p.pseudo::text from public.profiles p where p.id = l.actor_id),
               case when exists (select 1 from public.super_admins s where s.user_id = l.actor_id) then 'super admin' end),
      l.action,
      (select p.pseudo::text from public.profiles p where p.id = l.target_user_id),
      l.before, l.after
    from public.admin_team_log l
    order by l.created_at desc, l.id desc
    limit least(greatest(coalesce(p_limit, 100), 1), 500);
end;
$$;

