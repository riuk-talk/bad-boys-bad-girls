-- 3. A member account with a role leaves the site as a member
------------------------------------------------------------------------------------------------
-- An account with a role keeps hidden_reason « staff », whatever writes to its profile (a guard:
-- it cannot act as a member, the moderation cannot show it again).
create function private.profiles_staff_guard()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if exists (select 1 from public.admin_users a where a.user_id = new.id) then
    new.hidden_reason := 'staff';
  end if;
  return new;
end;
$$;
revoke execute on function private.profiles_staff_guard() from public, anon, authenticated, service_role;
create trigger profiles_staff_guard
  before insert or update on public.profiles
  for each row execute function private.profiles_staff_guard();

-- A role given: the profile is withdrawn (its hidden_reason kept to give it back), its requests
-- and visits closed with the usual neutral notices.
create function private.admin_users_hide_profile()
returns trigger language plpgsql security definer set search_path = '' as $$
declare previous text;
begin
  select p.hidden_reason into previous from public.profiles p where p.id = new.user_id for update;
  if found then
    new.previous_hidden_reason := case when previous = 'staff' then null else previous end;
  end if;
  return new;
end;
$$;
revoke execute on function private.admin_users_hide_profile() from public, anon, authenticated, service_role;
create trigger admin_users_hide_profile
  before insert on public.admin_users
  for each row execute function private.admin_users_hide_profile();

create function private.admin_users_after_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    -- The guard sets hidden_reason; the cases end as for a closed account.
    update public.profiles set hidden_reason = 'staff' where id = new.user_id;
    if found then perform private.close_cases_of(new.user_id, 'staff_role'); end if;
  elsif tg_op = 'DELETE' then
    -- The role taken back: the profile as it was.
    update public.profiles set hidden_reason = old.previous_hidden_reason where id = old.user_id;
  end if;
  return null;
end;
$$;
revoke execute on function private.admin_users_after_change() from public, anon, authenticated, service_role;
create trigger admin_users_after_change
  after insert or delete on public.admin_users
  for each row execute function private.admin_users_after_change();

-- The accounts that already have a role leave the site as members now (case of 2026-11-17).
update public.admin_users a set previous_hidden_reason = p.hidden_reason
from public.profiles p where p.id = a.user_id and p.hidden_reason is distinct from 'staff';
update public.profiles p set hidden_reason = 'staff'
where exists (select 1 from public.admin_users a where a.user_id = p.id);
select private.close_cases_of(a.user_id, 'staff_role') from public.admin_users a
where exists (select 1 from public.profiles p where p.id = a.user_id);

-- And an account with a role is never an active member, whatever its profile says.
create or replace function public.is_member_active(p public.profiles)
returns boolean language sql stable security definer set search_path = '' as $$
  select p.onboarding_completed_at is not null and p.banned_at is null and p.hidden_reason is null
    and (p.suspended_until is null or p.suspended_until <= now())
    and not exists (select 1 from public.admin_users a where a.user_id = p.id)
$$;

