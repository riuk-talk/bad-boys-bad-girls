create function public.has_admin_permission(p_permission text)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select auth.jwt() ->> 'aal') = 'aal2', false)
    and (exists (select 1 from public.super_admins where user_id = (select auth.uid()))
         or exists (select 1 from public.admin_users au
                    join public.admin_role_permissions rp on rp.role_id = au.role_id
                    where au.user_id = (select auth.uid()) and rp.permission = p_permission))
$$;
revoke execute on function public.has_admin_permission(text) from public, anon, service_role;
grant execute on function public.has_admin_permission(text) to authenticated;

-- What the connected admin may do (the menu, the pages): nothing before the second factor.
create function public.my_admin_permissions()
returns text[] language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(p.key order by p.position), '{}')
  from public.admin_permissions p
  where public.has_admin_permission(p.key)
$$;
revoke execute on function public.my_admin_permissions() from public, anon, service_role;
grant execute on function public.my_admin_permissions() to authenticated;

