  q text := btrim(coalesce(p_query, ''));
  pattern text;
begin
  if not public.has_admin_permission('members.view') then raise exception 'admin_only' using errcode = '42501'; end if;
  if char_length(q) < 2 or char_length(q) > 254 then return; end if;
  if position('@' in q) > 0 then
