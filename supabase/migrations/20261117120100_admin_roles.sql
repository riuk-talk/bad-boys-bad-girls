-- admin_save_tribe(text,text,text,smallint,boolean,smallint): signs.edit
CREATE OR REPLACE FUNCTION public.admin_save_tribe(p_slug text, p_label_fr text, p_label_en text, p_sort smallint, p_active boolean, p_tribe smallint DEFAULT NULL::smallint)
 RETURNS smallint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare saved smallint; fr text := btrim(coalesce(p_label_fr, '')); en text := btrim(coalesce(p_label_en, ''));
begin
  if not public.has_admin_permission('signs.edit') then raise exception 'admin_only' using errcode = '42501'; end if;
  if p_slug is null or p_slug !~ '^[a-z0-9-]{2,40}$' then raise exception 'invalid_slug' using errcode = '22023'; end if;
  if char_length(fr) not between 2 and 40 or char_length(en) not between 2 and 40 then
    raise exception 'invalid_label' using errcode = '22023';
  end if;
  if p_tribe is null then
    insert into public.tribes (slug, label, sort, is_active)
    values (p_slug, jsonb_build_object('fr', fr, 'en', en), coalesce(p_sort, 0), coalesce(p_active, true))
    returning id into saved;
  else
    update public.tribes set slug = p_slug, label = jsonb_build_object('fr', fr, 'en', en),
      sort = coalesce(p_sort, 0), is_active = coalesce(p_active, true)
    where id = p_tribe returning id into saved;
    if saved is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  end if;
  return saved;
exception when unique_violation then
  raise exception 'slug_taken' using errcode = '23505';
end;
$function$;

-- admin_web_vitals(integer): performance.view
CREATE OR REPLACE FUNCTION public.admin_web_vitals(p_days integer DEFAULT 28)
 RETURNS TABLE(page text, metric text, samples bigint, p75 double precision)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare since date := (now() at time zone 'Europe/Paris')::date - (least(greatest(coalesce(p_days, 28), 1), 90) - 1);
begin
  if not public.has_admin_permission('performance.view') then raise exception 'admin_only' using errcode = '42501'; end if;
  return query
    with h as (
      select w.page, w.metric, w.bucket, sum(w.samples)::bigint as n
      from public.web_vitals_daily w where w.day >= since
      group by w.page, w.metric, w.bucket
    ), c as (
      select h.*, sum(h.n) over (partition by h.page, h.metric order by h.bucket) as running,
        sum(h.n) over (partition by h.page, h.metric) as total
      from h
    )
    select c.page, c.metric, max(c.total)::bigint,
      (select (power(1.1, c2.bucket + 0.5) / case when c2.metric = 'CLS' then 1000 else 1 end)::double precision
       from c c2 where c2.page = c.page and c2.metric = c.metric and c2.running >= 0.75 * c2.total
       order by c2.bucket limit 1)
    from c group by c.page, c.metric
    order by c.page, c.metric;
end;
$function$;

